#!/usr/bin/env python3
"""Regenerate audio/opus/silk_tables_data.cst from RFC 6716.

This script is committed but was NOT run while the decoder was written: the
writing phase forbids executing generators. The committed data file was
transcribed from the RFC text and compared value-by-value against that same
text in that phase; this tool is the intended provenance path for the next
change. Treat its output as unverified until it has been run and diffed.

Usage:
    python3 tools/gen_opus_silk_tables.py --spec <rfc6716.txt> \
        -o audio/opus/silk_tables_data.cst

The RFC prints most SILK tables before their caption, as ASCII boxes. The
helpers below locate the block ending at a caption and then read either the
brace-delimited PDFs or the numeric rows. Tables that are not blobs (the
shell-block counts of Table 44, the quantization offsets of Table 53 are
small enough to read directly; the LCG seed PDF of Table 43 is uniform and
is decoded without a table) are handled by the decoder as constants.
"""

import argparse
import re
import sys


def block_before(lines, caption):
    """Lines between the previous table caption and `caption`."""
    idx = None
    for i, line in enumerate(lines):
        if caption in line:
            idx = i
            break
    if idx is None:
        raise ValueError("caption not found: " + caption)
    start = 0
    for j in range(idx - 1, -1, -1):
        if "Table " in lines[j] and ":" in lines[j]:
            start = j + 1
            break
    return lines[start:idx]


def brace_rows(block):
    """Every {...} group in the block, as a list of integers."""
    text = "\n".join(block)
    out = []
    for match in re.findall(r"\{([^}]*)\}", text, re.S):
        out.append([int(x) for x in re.findall(r"-?\d+", match)])
    return out


def numeric_rows(block):
    """Rows of an ASCII table whose label column (parts[1]) is a number."""
    out = []
    for line in block:
        parts = line.split("|")
        if len(parts) >= 4 and parts[1].strip().isdigit():
            out.append(parts)
    return out


def column(block, col):
    """Numeric values of one column (0-based Python split index)."""
    out = []
    for parts in numeric_rows(block):
        if len(parts) > col:
            out.extend(int(x) for x in re.findall(r"-?\d+", parts[col]))
    return out


def letters(block, mapping):
    """Map letter rows of a selection table to small integers."""
    out = []
    for line in block:
        parts = line.split("|")
        if len(parts) < 3:
            continue
        tokens = parts[2].split()
        if not tokens:
            continue
        ok = True
        for token in tokens:
            if token not in mapping:
                ok = False
                break
        if ok:
            out.extend(mapping[token] for token in tokens)
    return out


def sums_to_256(values):
    if sum(values) != 256:
        raise ValueError("PDF does not sum to 256: %r" % (values,))
    return values


def emit(out, name, values, pdf=False, expected=None):
    if expected is not None and len(values) != expected:
        raise ValueError("%s: expected %d values, got %d" %
                         (name, expected, len(values)))
    if pdf:
        for v in values:
            if v < 0 or v > 256:
                raise ValueError("%s: probability out of range" % name)
    out.write('let is *u8 as %s with imut = "%s";\n' %
              (name, ",".join(str(v) for v in values)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", required=True)
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args()

    with open(args.spec, "r", encoding="utf-8", errors="replace") as f:
        lines = f.read().splitlines()

    with open(args.output, "w", encoding="utf-8") as out:
        out.write("// Generated by tools/gen_opus_silk_tables.py from RFC 6716.\n")
        out.write("// See audio/opus/silk.md for the table list and checks.\n\n")

        t6 = brace_rows(block_before(lines, "Table 6: Stereo Weight PDFs"))
        emit(out, "SILK_TBL_STEREO_S1", sums_to_256(t6[0]), pdf=True, expected=25)
        emit(out, "SILK_TBL_STEREO_S2", sums_to_256(t6[1]), pdf=True, expected=3)
        emit(out, "SILK_TBL_STEREO_S3", sums_to_256(t6[2]), pdf=True, expected=5)

        emit(out, "SILK_TBL_STEREO_W",
             column(block_before(lines, "Table 7: Stereo Weight Table"), 2),
             expected=16)

        emit(out, "SILK_TBL_MID_ONLY",
             sums_to_256(brace_rows(block_before(lines, "Table 8:"))[0]),
             pdf=True, expected=2)

        t9 = brace_rows(block_before(lines, "Table 9:"))
        emit(out, "SILK_TBL_FRAME_INACTIVE", sums_to_256(t9[0]),
             pdf=True, expected=6)
        emit(out, "SILK_TBL_FRAME_ACTIVE", sums_to_256(t9[1]),
             pdf=True, expected=6)

        t11 = brace_rows(block_before(lines, "Table 11:"))
        emit(out, "SILK_TBL_GAIN_MSB_INACTIVE", sums_to_256(t11[0]),
             pdf=True, expected=8)
        emit(out, "SILK_TBL_GAIN_MSB_UNVOICED", sums_to_256(t11[1]),
             pdf=True, expected=8)
        emit(out, "SILK_TBL_GAIN_MSB_VOICED", sums_to_256(t11[2]),
             pdf=True, expected=8)

        emit(out, "SILK_TBL_GAIN_DELTA",
             sums_to_256(brace_rows(block_before(lines, "Table 13:"))[0]),
             pdf=True, expected=41)

        t14 = brace_rows(block_before(lines, "Table 14:"))
        for name, vals in zip(
                ["SILK_TBL_LSF_S1_NBMB_INACTIVE", "SILK_TBL_LSF_S1_NBMB_VOICED",
                 "SILK_TBL_LSF_S1_WB_INACTIVE", "SILK_TBL_LSF_S1_WB_VOICED"], t14):
            emit(out, name, sums_to_256(vals), pdf=True, expected=32)

        # Tables 15 and 16 together are the sixteen stage-2 PDFs a..h, i..p.
        s2 = []
        for vals in (brace_rows(block_before(lines, "Table 15:")) +
                     brace_rows(block_before(lines, "Table 16:"))):
            s2.extend(sums_to_256(vals))
        emit(out, "SILK_TBL_LSF_S2", s2, pdf=True, expected=144)

        emit(out, "SILK_TBL_LSF_S2_EXT",
             sums_to_256(brace_rows(block_before(lines, "Table 19:"))[0]),
             pdf=True, expected=7)

        t20 = block_before(lines, "Table 20:")
        emit(out, "SILK_TBL_LSF_PRED_A", column(t20, 2), expected=9)
        emit(out, "SILK_TBL_LSF_PRED_B", column(t20, 3), expected=9)
        emit(out, "SILK_TBL_LSF_PRED_C", column(t20, 4), expected=15)
        emit(out, "SILK_TBL_LSF_PRED_D", column(t20, 5), expected=15)

        # Table 17's I1 = 6 row is mislabelled "g" in the RFC; letters()
        # reads rows by their value field, so the label is irrelevant.
        ab = {"a": 0, "b": 1, "c": 2, "d": 3, "e": 4, "f": 5, "g": 6, "h": 7}
        emit(out, "SILK_TBL_LSF_S2_SEL_NBMB",
             letters(block_before(lines, "Table 17:"), ab), expected=320)
        ip = {"i": 0, "j": 1, "k": 2, "l": 3, "m": 4, "n": 5, "o": 6, "p": 7}
        emit(out, "SILK_TBL_LSF_S2_SEL_WB",
             letters(block_before(lines, "Table 18:"), ip), expected=512)

        emit(out, "SILK_TBL_LSF_PRED_SEL_NBMB",
             letters(block_before(lines, "Table 21:"), {"A": 0, "B": 1}),
             expected=288)
        emit(out, "SILK_TBL_LSF_PRED_SEL_WB",
             letters(block_before(lines, "Table 22:"), {"C": 0, "D": 1}),
             expected=480)

        emit(out, "SILK_TBL_LSF_CB_NBMB",
             column(block_before(lines, "Table 23:"), 2), expected=320)

        # Table 24 prints its I1 = 0 row twice (a typographic duplicate).
        wb_rows = numeric_rows(block_before(lines, "Table 24:"))
        if len(wb_rows) == 33 and wb_rows[0][2] == wb_rows[1][2]:
            wb_rows = wb_rows[:1] + wb_rows[2:]
        wb_vals = []
        for parts in wb_rows:
            wb_vals.extend(int(x) for x in re.findall(r"-?\d+", parts[2]))
        emit(out, "SILK_TBL_LSF_CB_WB", wb_vals, expected=512)

        t25 = block_before(lines, "Table 25:")
        emit(out, "SILK_TBL_LSF_MINSP_NBMB", column(t25, 2), expected=11)
        emit(out, "SILK_TBL_LSF_MINSP_WB", column(t25, 3), expected=17)

        emit(out, "SILK_TBL_LSF_INTERP",
             sums_to_256(brace_rows(block_before(lines, "Table 26:"))[0]),
             pdf=True, expected=5)

        t27 = block_before(lines, "Table 27:")
        emit(out, "SILK_TBL_LSF_ORDER_NBMB", column(t27, 2), expected=10)
        emit(out, "SILK_TBL_LSF_ORDER_WB", column(t27, 3), expected=16)

        cos_vals = []
        for parts in numeric_rows(block_before(lines, "Table 28:")):
            for c in range(2, 6):
                if len(parts) > c:
                    cos_vals.extend(int(x) for x in re.findall(r"-?\d+", parts[c]))
        emit(out, "SILK_TBL_COS", cos_vals, expected=129)

        emit(out, "SILK_TBL_PITCH_HIGH",
             sums_to_256(brace_rows(block_before(lines, "Table 29:"))[0]),
             pdf=True, expected=32)

        t30 = brace_rows(block_before(lines, "Table 30:"))
        emit(out, "SILK_TBL_PITCH_LOW_NB", sums_to_256(t30[0]),
             pdf=True, expected=4)
        emit(out, "SILK_TBL_PITCH_LOW_MB", sums_to_256(t30[1]),
             pdf=True, expected=6)
        emit(out, "SILK_TBL_PITCH_LOW_WB", sums_to_256(t30[2]),
             pdf=True, expected=8)

        emit(out, "SILK_TBL_PITCH_DELTA",
             sums_to_256(brace_rows(block_before(lines, "Table 31:"))[0]),
             pdf=True, expected=21)

        t32 = brace_rows(block_before(lines, "Table 32:"))
        for name, vals, count in [
                ("SILK_TBL_CONTOUR_PDF_NB10", t32[0], 3),
                ("SILK_TBL_CONTOUR_PDF_NB20", t32[1], 11),
                ("SILK_TBL_CONTOUR_PDF_MBWB10", t32[2], 12),
                ("SILK_TBL_CONTOUR_PDF_MBWB20", t32[3], 34)]:
            emit(out, name, sums_to_256(vals), pdf=True, expected=count)

        emit(out, "SILK_TBL_CONTOUR_CB_NB10",
             column(block_before(lines, "Table 33:"), 2), expected=6)
        emit(out, "SILK_TBL_CONTOUR_CB_NB20",
             column(block_before(lines, "Table 34:"), 2), expected=44)
        emit(out, "SILK_TBL_CONTOUR_CB_MBWB10",
             column(block_before(lines, "Table 35:"), 2), expected=24)
        emit(out, "SILK_TBL_CONTOUR_CB_MBWB20",
             column(block_before(lines, "Table 36:"), 2), expected=136)

        emit(out, "SILK_TBL_LTP_PERIOD",
             sums_to_256(brace_rows(block_before(lines, "Table 37:"))[0]),
             pdf=True, expected=3)

        t38 = brace_rows(block_before(lines, "Table 38:"))
        for name, vals, count in [("SILK_TBL_LTP_PDF0", t38[0], 8),
                                  ("SILK_TBL_LTP_PDF1", t38[1], 16),
                                  ("SILK_TBL_LTP_PDF2", t38[2], 32)]:
            emit(out, name, sums_to_256(vals), pdf=True, expected=count)

        emit(out, "SILK_TBL_LTP_CB0",
             column(block_before(lines, "Table 39:"), 2), expected=40)
        emit(out, "SILK_TBL_LTP_CB1",
             column(block_before(lines, "Table 40:"), 2), expected=80)
        emit(out, "SILK_TBL_LTP_CB2",
             column(block_before(lines, "Table 41:"), 2), expected=160)

        emit(out, "SILK_TBL_LTP_SCALE_PDF",
             sums_to_256(brace_rows(block_before(lines, "Table 42:"))[0]),
             pdf=True, expected=3)
        # The three Q14 scale values are in the prose of section 4.2.7.6.3,
        # not in an ASCII table: 15565, 12288 and 8192.
        emit(out, "SILK_TBL_LTP_SCALE", [15565, 12288, 8192], expected=3)

        t45 = brace_rows(block_before(lines, "Table 45:"))
        emit(out, "SILK_TBL_EXC_RATE_INACTIVE", sums_to_256(t45[0]),
             pdf=True, expected=9)
        emit(out, "SILK_TBL_EXC_RATE_VOICED", sums_to_256(t45[1]),
             pdf=True, expected=9)

        counts = []
        for vals in brace_rows(block_before(lines, "Table 46:")):
            counts.extend(sums_to_256(vals))
        emit(out, "SILK_TBL_PULSE_COUNT", counts, pdf=True, expected=198)

        for caption, name in [
                ("Table 47:", "SILK_TBL_PULSE_SPLIT16"),
                ("Table 48:", "SILK_TBL_PULSE_SPLIT8"),
                ("Table 49:", "SILK_TBL_PULSE_SPLIT4"),
                ("Table 50:", "SILK_TBL_PULSE_SPLIT2")]:
            vals = []
            for group in brace_rows(block_before(lines, caption)):
                vals.extend(sums_to_256(group))
            emit(out, name, vals, pdf=True, expected=152)

        emit(out, "SILK_TBL_LSB",
             sums_to_256(brace_rows(block_before(lines, "Table 51:"))[0]),
             pdf=True, expected=2)

        sign_vals = []
        for group in brace_rows(block_before(lines, "Table 52:")):
            sign_vals.extend(sums_to_256(group))
        emit(out, "SILK_TBL_SIGN", sign_vals, pdf=True, expected=84)

        # Table 53 has word labels; its last column is the Q23 offset.
        qoff = []
        for line in block_before(lines, "Table 53:"):
            parts = line.split("|")
            if len(parts) >= 4 and parts[3].strip().isdigit():
                qoff.append(int(parts[3]))
        emit(out, "SILK_TBL_QOFF", qoff, expected=6)

        t4 = brace_rows(block_before(lines, "Table 4:"))
        emit(out, "SILK_TBL_LBRR40", sums_to_256(t4[0]), pdf=True, expected=4)
        emit(out, "SILK_TBL_LBRR60", sums_to_256(t4[1]), pdf=True, expected=8)

    return 0


if __name__ == "__main__":
    sys.exit(main())
