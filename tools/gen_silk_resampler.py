#!/usr/bin/env python3
"""Generate audio/opus/silk_resample_data.cst: minimum-phase 48 kHz interpolators.

A linear-phase filter with good image rejection is too late for the delay Opus
expects from SILK. A minimum-phase filter keeps the magnitude response of the
long prototype with a small delay at low frequencies, and a pure delay then
lands it exactly on the target. Run with: python3 tools/gen_silk_resampler.py
Needs numpy. Writes coefficients in Q30, phase by phase.
"""
import numpy as np, sys
TAPS = 65
# name, input rate, cutoff Hz, half-width in input samples, target LF delay at 48 kHz
SETS = [("NB", 8000, float(sys.argv[1]) if len(sys.argv) > 1 else 4000.0, 26),
        ("MB", 12000, float(sys.argv[2]) if len(sys.argv) > 2 else 6000.0, 33),
        ("WB", 16000, float(sys.argv[3]) if len(sys.argv) > 3 else 8000.0, 34)]
BETA = float(sys.argv[4]) if len(sys.argv) > 4 else 9.0
def design(rate, cutoff, target):
    L = 48000 // rate
    half = L * 24
    n = np.arange(-half, half + 1)
    h = (2 * cutoff / 48000) * np.sinc(2 * cutoff / 48000 * n) * np.kaiser(len(n), BETA)
    h = h / h.sum()
    N = 1 << 16
    H = np.abs(np.fft.fft(h, N))
    H = np.maximum(H, 1e-7)
    c = np.fft.ifft(np.log(H)).real
    w = np.zeros(N); w[0] = 1; w[1:N // 2] = 2; w[N // 2] = 1
    mp = np.fft.ifft(np.exp(np.fft.fft(c * w))).real
    gd = np.sum(np.arange(N) * mp) / np.sum(mp)
    d = int(round(target - gd))
    if d < 0:
        raise SystemExit("rate %d: minimum-phase delay %.1f exceeds target %d" % (rate, gd, target))
    room = TAPS * L - d
    out = np.concatenate([np.zeros(d), mp[:room]])
    out = out / out.sum()
    return L, out, gd, d
lines = ["// =======================================================",
         "// caustic-av/audio/opus/silk_resample_data.cst",
         "// Generated by tools/gen_silk_resampler.py. Do not edit.",
         "// Minimum-phase interpolators to 48 kHz, Q30, coef[p][j] in order, comma",
         "// separated: taps %d, phases 6 (NB), 4 (MB), 3 (WB)." % TAPS,
         "// ======================================================="]
for name, rate, cutoff, target in SETS:
    L, h, gd, d = design(rate, cutoff, target)
    print("%s L=%d group delay %.2f pure %d" % (name, L, gd, d), file=sys.stderr)
    vals = []
    for p in range(L):
        for j in range(TAPS):
            vals.append(int(round(h[p + j * L] * L * (1 << 30))))
    lines.append('let is *u8 as SILK_RS48_%s with imut = "%s";' % (name, ",".join(map(str, vals))))
open("audio/opus/silk_resample_data.cst", "w").write("\n".join(lines) + "\n")
